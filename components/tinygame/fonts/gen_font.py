#!/usr/bin/env python3
"""Rasterises Space Grotesk (SIL OFL, see OFL.txt) into 2-bit anti-aliased bitmap fonts for the OS.

Run:  python3 gen_font.py   (needs Pillow)   ->  ../font_aa.c
Four sizes (em in px, weight): S 13/600, M 16/700, L 24/700, XL 32/700. ASCII 32..126.
A glyph's y offset is measured from the top of the capital letters, so text is placed by cap top.
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
SIZES = [("S", 13, 600), ("M", 16, 700), ("L", 24, 700), ("XL", 32, 700)]

def level(v):
    return 0 if v < 40 else 1 if v < 110 else 2 if v < 190 else 3

out = ['// Generated by fonts/gen_font.py from Space Grotesk (SIL Open Font License). Do not edit.',
       '#include "font_aa.h"', '']
tables = []
for name, em, wght in SIZES:
    f = ImageFont.truetype(os.path.join(HERE, "SpaceGrotesk.ttf"), em)
    f.set_variation_by_axes([wght])
    cap = -f.getbbox("H", anchor="ls")[1]
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        pad = em
        img = Image.new("L", (adv + 2 * pad, em * 3), 0)
        ImageDraw.Draw(img).text((pad, em * 2), ch, font=f, fill=255, anchor="ls")
        box = img.getbbox()
        if box is None:
            glyphs.append((0, 0, 0, 0, adv, len(bits)))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        px = img.crop(box).load()
        start = len(bits)
        for y in range(h):
            row = 0
            for x in range(w):
                row = (row << 2) | level(px[x, y])
                if (x & 3) == 3:
                    bits.append(row); row = 0
            if w & 3:
                bits.append(row << (2 * (4 - (w & 3))))
        glyphs.append((w, h, x0 - pad, (y0 - em * 2) + cap, adv, start))
    line = ascent + descent
    out.append(f"static const uint8_t BITS_{name}[] = {{")
    for i in range(0, len(bits), 24):
        out.append("    " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const aa_glyph_t GLYPHS_{name}[95] = {{")
    for g in glyphs:
        out.append("    {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    tables.append(f"    {{ {cap}, {line}, GLYPHS_{name}, BITS_{name} }},")
out.append("const aa_font_t FONT_AA[4] = {")
out += tables
out.append("};")
open(os.path.join(HERE, "..", "font_aa.c"), "w").write("\n".join(out) + "\n")
print("wrote font_aa.c")
